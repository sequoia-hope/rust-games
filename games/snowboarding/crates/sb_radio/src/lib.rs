//! The game's commentary: the two television announcers who call the runs
//! of the Ten-Eighty Mountain Series ([`script`]), and the [`director`]
//! that decides when they speak and what they say, from the run's events.
//! The music under them is `sb_music`'s station; the client plays both
//! (`sb_game::audio`).
//!
//! Engine-free and clock-free like the simulation: the client feeds the
//! director what happened and how much time passed, and plays the clips it
//! asks for. The recordings are `audio/announcers/<clip>.mp3`, made by
//! `tools/announcers/` from [`script_json`].

pub mod director;
pub mod script;

/// Who is speaking.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Who {
    Dani,
    Wren,
}

impl Who {
    pub fn key(self) -> &'static str {
        match self {
            Who::Dani => "dani",
            Who::Wren => "wren",
        }
    }
    pub fn name(self) -> &'static str {
        match self {
            Who::Dani => "Dani",
            Who::Wren => "Wren",
        }
    }
}

/// A line's clip: `<topic>-<bit>-<line>`, counted from 1.
pub fn clip_id(topic: &str, bit: usize, line: usize) -> String {
    format!("{topic}-{}-{}", bit + 1, line + 1)
}

/// A topic's bits.
pub fn topic(key: &str) -> &'static [script::Bit] {
    script::TOPICS
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, b)| *b)
        .unwrap_or(&[])
}

fn json_str(s: &str) -> String {
    let mut o = String::with_capacity(s.len() + 2);
    o.push('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// The script as `tools/announcers/lines.json`: every clip in order, with
/// its speaker and words (`render.py` records them).
pub fn script_json() -> String {
    let mut out = String::from("{\n \"about\": \"Generated by `cargo run -p sb_radio --example script`, from crates/sb_radio/src/script.rs; do not edit.\",\n \"clips\": [\n");
    let mut first = true;
    for (topic, bits) in script::TOPICS {
        for (b, bit) in bits.iter().enumerate() {
            for (l, (who, text)) in bit.iter().enumerate() {
                if !first {
                    out.push_str(",\n");
                }
                first = false;
                out.push_str(&format!(
                    "  {{\"id\": {}, \"who\": {}, \"text\": {}}}",
                    json_str(&clip_id(topic, b, l)),
                    json_str(who.key()),
                    json_str(text)
                ));
            }
        }
    }
    out.push_str("\n ]\n}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_checked_in_script_is_current() {
        let file = include_str!("../../../tools/announcers/lines.json");
        assert!(
            file == script_json(),
            "tools/announcers/lines.json is stale: cargo run -p sb_radio --example script > tools/announcers/lines.json"
        );
    }

    #[test]
    fn every_topic_has_bits_and_every_bit_lines() {
        let mut keys = std::collections::HashSet::new();
        for (k, bits) in script::TOPICS {
            assert!(keys.insert(*k), "topic {k} twice");
            assert!(!bits.is_empty(), "{k}: no bits");
            for b in *bits {
                assert!(!b.is_empty(), "{k}: an empty bit");
                for (_, t) in *b {
                    assert!(!t.trim().is_empty());
                    assert!(!t.chars().any(|c| c.is_ascii_digit()), "{k}: digits are read badly: {t}");
                }
            }
        }
    }
}
